#!/usr/bin/env python3
# --------------------
# --    build.py    --
# --------------------
# description: Generate the photo site in site/ from photos/ and photos/captions.csv
"""Generate the photo site from photos/ and its captions.

  scripts/site/build.py

The starting builder for a photo site (docs/photo-sites.md in the standards
repository). A real site extends it, for example with pages rendered from
its Markdown records; keep the outputs and conventions below when it does.
Writes, all git-ignored:

  site/index.html        one page: an intro, a bar of section links once
                         there are two or more sections, and one section per
                         folder under photos/
  site/thumbs/*.jpg      grid thumbnails, 1200px, no metadata but the color
                         profile; made only when missing or older than the
                         photo
  site/routes.json       clean URLs (each section's slug loads the home page
                         at that section); serve.py reads it
  site/htaccess          the same routes as Apache rewrite rules, deployed as
                         .htaccess by build-deploy.sh

Photo titles and descriptions come from photos/captions.csv, with the
columns file,title,description,kind; a row whose file ends in "/" captions a
folder. Only the capture date reaches the page, never the time or place.
CSS and JS links carry ?v=<content hash>, and pages are no-cache, so a
deploy is never hidden by a cached copy.

serve.py runs this before serving any page, so edits show up on reload.
"""

import csv
import hashlib
import html
import json
import re
from pathlib import Path
from urllib.parse import quote

from PIL import Image, ImageOps

REPO = Path(__file__).resolve().parents[2]
PHOTOS = REPO / "photos"
SITE = REPO / "site"
THUMBS = SITE / "thumbs"
ROUTES = SITE / "routes.json"
HTACCESS = SITE / "htaccess"
CAPTIONS = PHOTOS / "captions.csv"
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp"}
THUMB_EDGE = 1200

# Per-site settings.
TITLE = "Project title"
KICKER = "A short line above the title"
LEAD = "One or two sentences that say what the project is."
# Where the site is published (bin/deploy's SUBDIR); Apache resolves
# redirects against it.
PUBLIC_BASE = "/project/"
# Photo folders in display order; any other folder with images follows.
PHOTO_ORDER = []
# Short URL slugs for sections (/<project>/<slug>); folders not listed here
# use their last folder name. Never repeat the project's name in a slug.
SECTION_SLUGS = {}

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<!-- Generated by scripts/site/build.py. Don't edit by hand. -->
<title>{title}</title>
<link rel="preload" href="/assets/typefaces/sansserif/NothingSans-Book.otf" as="font" type="font/otf" crossorigin>
<link rel="preload" href="/assets/typefaces/sansserif/NothingSans-Light.otf" as="font" type="font/otf" crossorigin>
<link rel="preload" href="/assets/typefaces/sansserif/NothingSans-SemiBold.otf" as="font" type="font/otf" crossorigin>
<link rel="preload" href="/assets/typefaces/sansserif/NothingSans-Bold.otf" as="font" type="font/otf" crossorigin>
<link rel="stylesheet" href="/assets/css/base.css">
<link rel="stylesheet" href="/assets/css/gallery.css">
<link rel="stylesheet" href="/assets/css/typography.css">
<script>
// Apply a saved Light or Dark choice before first paint (assets/js/theme.js).
try {{
	var t = localStorage.getItem('theme');
	if (t === 'light' || t === 'dark') document.documentElement.setAttribute('data-theme', t);
}} catch (e) {{}}
</script>
<script>
// Hide the page until the Nothing Sans faces are loaded, then fade it in
// (styles in assets/css/typography.css), so the system font never flashes
// first. Gives up after 3 seconds; without JavaScript nothing is ever hidden.
(function () {{
	var root = document.documentElement;
	function ready() {{
		root.classList.remove('fonts-loading');
		root.classList.add('fonts-ready');
	}}
	if (!document.fonts || !document.fonts.load) return;
	root.classList.add('fonts-loading');
	var timer = setTimeout(ready, 3000);
	Promise.all([
		'400 1em "Nothing Sans"', '700 1em "Nothing Sans"', '800 1em "Nothing Sans"', '400 1em "Nothing Sans Light"'
	].map(function (f) {{ return document.fonts.load(f); }})).then(done, done);
	function done() {{ clearTimeout(timer); ready(); }}
}})();
</script>
<script src="/assets/js/viewer.js" defer></script>
<script src="/assets/js/jump.js" defer></script>
<script src="/assets/js/theme.js" defer></script>
</head>
<body>
<nav class="series-nav"><a href="/">{site}</a></nav>
"""

TAIL = "</body>\n</html>\n"

HTACCESS_RULES = """# Generated by scripts/site/build.py from the same routes serve.py uses;
# deployed as .htaccess by scripts/site/build-deploy.sh. Don't edit by hand.

Options -Indexes -MultiViews
RewriteEngine On
RewriteBase {base}
{sections}
# Pages revalidate on every visit, so a deploy shows up at once. CSS and JS
# links carry ?v=<content hash>, so a change gets a new URL.
<IfModule mod_headers.c>
	<FilesMatch "\\.html$">
		Header set Cache-Control "no-cache"
	</FilesMatch>
</IfModule>
"""

SECTION_RULES = """
# Sections load the home page; assets/js/jump.js lands on the section. A
# section slug can also be a folder, and Apache would otherwise redirect it
# to a trailing slash before these rules run, so that is turned off for
# section paths only. A slash typed by hand is removed, since the page's
# relative links only work without it.
<If "%{{REQUEST_URI}} =~ m#^{base}({sections})/?$#">
	DirectorySlash Off
</If>
RewriteRule ^({sections})/$ $1 [R=301,L]
RewriteRule ^({sections})$ index.html [L]
"""


def esc(s):
	return html.escape(s or "", quote=True)


def slug(text):
	return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def section_slug(folder):
	return SECTION_SLUGS.get(folder) or slug(Path(folder).name)


def photo_id(rel):
	"""'trip/01 First Light.jpg' -> 'trip-01-first-light'"""
	return slug(str(Path(rel).with_suffix("")))


def read_captions():
	if not CAPTIONS.is_file():
		return {}
	with CAPTIONS.open(newline="", encoding="utf-8") as f:
		return {row["file"]: row for row in csv.DictReader(f) if row.get("file")}


def captured_on(path):
	"""The capture date ('2026-05-31') from EXIF, or ''. Never the time."""
	try:
		with Image.open(path) as im:
			raw = im.getexif().get_ifd(0x8769).get(36867) or im.getexif().get(306)
	except (OSError, ValueError):
		return ""
	m = re.match(r"(\d{4}):(\d{2}):(\d{2})", str(raw or ""))
	return "-".join(m.groups()) if m else ""


def thumbnail(path, rel):
	"""A thumbnail in site/thumbs/ that keeps only the color profile."""
	out = THUMBS / (photo_id(rel) + ".jpg")
	if out.is_file() and out.stat().st_mtime >= path.stat().st_mtime:
		return out
	THUMBS.mkdir(parents=True, exist_ok=True)
	with Image.open(path) as im:
		# iPhone photos are wide-color (Display P3); without the profile
		# browsers show them flatter, as sRGB.
		icc = im.info.get("icc_profile")
		im = ImageOps.exif_transpose(im).convert("RGB")
		im.thumbnail((THUMB_EDGE, THUMB_EDGE))
		tmp = out.with_suffix(".tmp")
		im.save(tmp, "JPEG", quality=82, optimize=True, **({"icc_profile": icc} if icc else {}))
	tmp.replace(out)
	return out


def version(rel):
	"""A short hash of a site/ file's content, for ?v= cache-busting."""
	return hashlib.sha256((SITE / rel).read_bytes()).hexdigest()[:10]


def page(title, body, root):
	"""Assemble a page. Links are written site-absolute ("/assets/...") while
	building, then made relative to the page (root is "" for a page at the
	site's top, "../" one folder down), so the site works both at the local
	server's root and under the published folder."""
	text = HEAD.format(title=esc(title), site=esc(TITLE)) + body + TAIL
	text = re.sub(r'(href|src)="/(assets/(?:css|js)/[^"?]+)"', lambda m: f'{m.group(1)}="/{m.group(2)}?v={version(m.group(2))}"', text)
	text = re.sub(r'(href|src|data-full)="/"', lambda m: f'{m.group(1)}="{root or "./"}"', text)
	return re.sub(r'(href|src|data-full)="/(?!/)', lambda m: f'{m.group(1)}="{root}', text)


def photo_folders():
	if not PHOTOS.is_dir():
		return []
	found = sorted({p.parent.relative_to(PHOTOS).as_posix() for p in PHOTOS.rglob("*")
		if p.suffix.lower() in IMAGE_EXT and not any(s.startswith(".") for s in p.relative_to(PHOTOS).parts)})
	return [f for f in PHOTO_ORDER if f in found] + [f for f in found if f not in PHOTO_ORDER]


def figure(rel, cap):
	path = PHOTOS / rel
	thumb = thumbnail(path, rel)
	title = (cap or {}).get("title") or Path(rel).stem
	desc = (cap or {}).get("description", "")
	kind = (cap or {}).get("kind", "")
	day = captured_on(path)
	meta = [m for m in (kind, f'<time datetime="{esc(day)}">{esc(day)}</time>' if day else "") if m]
	if cap is None:
		meta.append('<span class="flag">not in captions.csv</span>')
	return (
		f'  <figure data-photo="{esc(photo_id(rel))}" data-date="{esc(day)}">\n'
		f'    <img src="/thumbs/{esc(thumb.name)}" data-full="/photos/{esc(quote(rel))}" alt="{esc(title)}" loading="lazy" decoding="async">\n'
		f'    <figcaption><span class="photo-name">{esc(title)}</span>{esc(desc)}'
		f'<span class="photo-meta">{" &middot; ".join(meta)}</span></figcaption>\n'
		f"  </figure>\n"
	)


def photo_section(folder, captions):
	path = PHOTOS / folder
	names = sorted(p.name for p in path.iterdir() if p.suffix.lower() in IMAGE_EXT and not p.name.startswith("."))
	head = captions.get(folder + "/", {})
	count = len(names)
	return (
		f'<header class="series-head" id="{esc(section_slug(folder))}">\n'
		f'  <p class="kicker">photos/{esc(folder)}</p>\n'
		f"  <h2>{esc(head.get('title') or folder)}</h2>\n"
		+ (f'  <p class="lead">{esc(head["description"])}</p>\n' if head.get("description") else "")
		+ f'  <p class="series-count"><span class="count">{count}</span> photo{"" if count == 1 else "s"}</p>\n'
		f"</header>\n"
		f'<main class="gallery">\n'
		+ "".join(figure(f"{folder}/{n}", captions.get(f"{folder}/{n}")) for n in names)
		+ "</main>\n"
	)


def build_index(folders, captions):
	sections = [(section_slug(f), captions.get(f + "/", {}).get("title") or f) for f in folders]
	jump = ""
	if len(sections) >= 2:
		links = "".join(f'<a href="/{esc(s)}" data-section="{esc(s)}">{esc(label)}</a>' for s, label in sections)
		jump = f'<nav class="jump" aria-label="On this page">{links}</nav>\n'
	body = (
		'<header class="intro">\n'
		f'  <p class="kicker">{esc(KICKER)}</p>\n'
		f"  <h1>{esc(TITLE)}</h1>\n"
		f'  <p class="lead">{esc(LEAD)}</p>\n'
		"</header>\n"
		+ jump
		+ ("".join(photo_section(f, captions) for f in folders) or '<p class="pending">No photo folders in photos/ yet.</p>\n')
	)
	return page(TITLE, body, "")


def write(path, text):
	path.parent.mkdir(parents=True, exist_ok=True)
	tmp = path.with_suffix(".tmp")
	tmp.write_text(text, encoding="utf-8")
	tmp.replace(path)


def build():
	captions = read_captions()
	folders = photo_folders()
	sections = [section_slug(f) for f in folders]
	write(SITE / "index.html", build_index(folders, captions))
	write(ROUTES, json.dumps({"base": PUBLIC_BASE, "sections": sections, "pages": {"": "index.html"}, "redirects": {}}, indent=1) + "\n")
	write(HTACCESS, HTACCESS_RULES.format(base=PUBLIC_BASE,
		sections=SECTION_RULES.format(base=PUBLIC_BASE, sections="|".join(sections)) if sections else ""))
	return SITE / "index.html"


if __name__ == "__main__":
	build()
	print(f"Wrote site/index.html for {len(json.loads(ROUTES.read_text())['sections'])} sections, routes.json, and htaccess")
